#!/usr/bin/env node
// Build-size budget gate (S03-SR-15..S03-SR-18).
//
// Measures the production webpack bundle and the packaged .vsix, fails
// (exit 1) if either exceeds its budget, warns above 85% of budget, and
// writes the measurement to bundle-size.json (repo root, git-tracked, not
// shipped in the .vsix — see .vscodeignore) so the size trend over time is
// readable from that file's git history, the same pattern maturity-score.mjs
// uses for the maturity score.
//
// Usage:
//   npm run package && node scripts/check-bundle-size.mjs
//
// Requires dist/extension.js to already exist (run `npm run package` first) —
// this script only measures, it doesn't build.

import { existsSync, statSync, writeFileSync, unlinkSync, readFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { execFileSync } from 'child_process';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_PATH = join(ROOT, 'bundle-size.json');

// Budgets per S03-SR-16. extension.js is the activation bundle only — lazy
// chunks (dist/chunk-*.js) load on first use and count toward the .vsix.
const BUNDLE_BUDGET_BYTES = 1 * 1024 * 1024;
const VSIX_BUDGET_BYTES = 1.5 * 1024 * 1024;
const WARN_RATIO = 0.85;

function formatBytes(bytes) {
  return `${(bytes / (1024 * 1024)).toFixed(2)} MB`;
}

function measureBundle() {
  const bundlePath = join(ROOT, 'dist', 'extension.js');
  if (!existsSync(bundlePath)) {
    console.error('dist/extension.js not found — run `npm run package` first.');
    process.exit(1);
  }
  return statSync(bundlePath).size;
}

function measureVsix() {
  const vsixPath = join(ROOT, '__bundle-size-check.vsix');
  try {
    execFileSync(
      'npx',
      ['@vscode/vsce', 'package', '--no-dependencies', '-o', vsixPath],
      { cwd: ROOT, stdio: 'pipe' }
    );
    return statSync(vsixPath).size;
  } finally {
    if (existsSync(vsixPath)) unlinkSync(vsixPath);
  }
}

function report(label, bytes, budgetBytes) {
  const ratio = bytes / budgetBytes;
  const overBudget = bytes > budgetBytes;
  const nearBudget = !overBudget && ratio >= WARN_RATIO;
  const icon = overBudget ? '✗' : nearBudget ? '⚠' : '✓';
  console.log(
    `${icon} ${label.padEnd(20)} ${formatBytes(bytes).padStart(9)}  ` +
    `(budget ${formatBytes(budgetBytes)}, ${(ratio * 100).toFixed(1)}%)`
  );
  if (overBudget) {
    console.error(`  ${label} exceeds its budget by ${formatBytes(bytes - budgetBytes)}.`);
  } else if (nearBudget) {
    console.warn(`  ${label} is within ${((1 - ratio) * 100).toFixed(1)}% of its budget — watch for further growth.`);
  }
  return !overBudget;
}

const bundleBytes = measureBundle();
const vsixBytes = measureVsix();

const bundleOk = report('extension.js', bundleBytes, BUNDLE_BUDGET_BYTES);
const vsixOk = report('packaged .vsix', vsixBytes, VSIX_BUDGET_BYTES);

const packageJson = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf-8'));

writeFileSync(
  OUT_PATH,
  JSON.stringify(
    {
      $comment: 'Generated by scripts/check-bundle-size.mjs — do not edit by hand. Run `npm run package && npm run check:bundle-size` to refresh.',
      generatedAt: new Date().toISOString().slice(0, 10),
      version: packageJson.version,
      measurements: {
        extensionBundleBytes: bundleBytes,
        extensionBundleBudgetBytes: BUNDLE_BUDGET_BYTES,
        vsixBytes: vsixBytes,
        vsixBudgetBytes: VSIX_BUDGET_BYTES,
      },
    },
    null,
    2
  ) + '\n'
);

if (!bundleOk || !vsixOk) {
  console.error('\nBuild size budget exceeded (S03-SR-16) — see specs/S03-performance.md.');
  process.exit(1);
}
console.log('\nAll build size budgets met.');
