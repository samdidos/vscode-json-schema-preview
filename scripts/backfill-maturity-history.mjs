#!/usr/bin/env node
// Reconstruct maturity-history/ from the git history of maturity-score.json
// (S12-SR-10). One snapshot is written per commit whose rounded score state
// differs from the preceding one, timestamped from the commit date — so the
// folder tells the same story the repository does. The folder is REBUILT from
// scratch on every run (existing *.json files are removed first), which makes
// re-running against an unchanged history idempotent; any uncommitted
// snapshot the scorer wrote is simply re-created on the next `npm run
// maturity` if the scores still differ.
//
// Usage: node scripts/backfill-maturity-history.mjs   (or: npm run maturity:backfill)
//
// Needs full git history — run `git fetch --unshallow` first in shallow CI clones.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { execSync } from 'child_process';
import { HISTORY_DIR, toSnapshot, sameScores, snapshotFileName } from './maturity-history-lib.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SCORE_FILE = 'maturity-score.json';

const git = (cmd) => execSync(`git ${cmd}`, { cwd: ROOT, encoding: 'utf-8' });

// Slugs for score files that predate the `slug` field: map labels through the
// current score file so history and criteria pages stay linked.
const current = JSON.parse(readFileSync(join(ROOT, SCORE_FILE), 'utf-8'));
const slugByLabel = Object.fromEntries(current.dimensions.map((d) => [d.label, d.slug]));

// Oldest → newest commits that touched the score file.
const commits = git(`log --follow --format="%H|%cI" -- ${SCORE_FILE}`)
  .trim()
  .split('\n')
  .filter(Boolean)
  .map((line) => { const [sha, at] = line.split('|'); return { sha, at }; })
  .reverse();

if (commits.length === 0) {
  console.error(`No commits touch ${SCORE_FILE} — is this a shallow clone? Try: git fetch --unshallow`);
  process.exit(1);
}

const dir = join(ROOT, HISTORY_DIR);
if (existsSync(dir)) {
  for (const f of readdirSync(dir)) if (f.endsWith('.json')) rmSync(join(dir, f));
}
mkdirSync(dir, { recursive: true });

let prev = null;
let written = 0;
const used = new Set();
for (const { sha, at } of commits) {
  let parsed;
  try {
    parsed = JSON.parse(git(`show ${sha}:${SCORE_FILE}`));
  } catch {
    continue; // file absent/unreadable at this commit (e.g. deleted then re-added)
  }
  const snapshot = toSnapshot(parsed, new Date(at).toISOString().slice(0, 19) + 'Z', slugByLabel);
  if (prev && sameScores(prev, snapshot)) { prev = snapshot; continue; }
  // Batch pushes can share one committer timestamp; suffix to keep every state.
  let name = snapshotFileName(snapshot.at);
  for (let i = 2; used.has(name); i++) name = snapshotFileName(snapshot.at, `-${i}`);
  used.add(name);
  writeFileSync(join(dir, name), JSON.stringify({
    $comment: 'Generated by scripts/backfill-maturity-history.mjs from git history. Do not edit by hand.',
    commit: sha.slice(0, 7),
    // Chronological tie-break for snapshots sharing a committer timestamp
    // (batch pushes) — readHistory() sorts on (at, seq).
    seq: written + 1,
    ...snapshot,
  }, null, 2) + '\n');
  written++;
  prev = snapshot;
}

console.log(`Backfilled ${written} score change(s) from ${commits.length} commit(s) into ${HISTORY_DIR}/`);
